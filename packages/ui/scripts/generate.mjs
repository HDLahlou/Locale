// Generates CSS, TypeScript and Dart from tokens.json and labels.json.
// Usage: node scripts/generate.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(root, "../..");
const COMMAND = "pnpm -C packages/ui generate";

const tokens = JSON.parse(readFileSync(resolve(root, "tokens.json"), "utf8"));
const labels = JSON.parse(readFileSync(resolve(root, "labels.json"), "utf8"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const dartHex = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;
const HEADER =
  "Generated by `pnpm -C packages/ui generate` from tokens.json and labels.json. Do not edit.";

function colorBlock(theme, indent) {
  return Object.entries(tokens.colors[theme])
    .map(([k, v]) => `${indent}--lc-${kebab(k)}: ${v};`)
    .join("\n");
}

function css() {
  const scales = [
    ...Object.entries(tokens.spacing).map(([k, v]) => `  --lc-space-${k}: ${v}px;`),
    ...Object.entries(tokens.radius).map(([k, v]) => `  --lc-radius-${k}: ${v}px;`),
    `  --lc-font-family: ${tokens.type.family};`,
    ...Object.entries(tokens.type.sizes).map(([k, v]) => `  --lc-text-${k}: ${v}px;`),
    ...Object.entries(tokens.type.weights).map(([k, v]) => `  --lc-weight-${k}: ${v};`),
    ...Object.entries(tokens.type.lineHeights).map(([k, v]) => `  --lc-leading-${k}: ${v};`),
  ].join("\n");
  return `/* ${HEADER} */
:root {
  color-scheme: light dark;
${scales}
}

:root,
[data-theme="light"] {
${colorBlock("light", "  ")}
}

[data-theme="light"] {
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${colorBlock("dark", "    ")}
  }
}

[data-theme="dark"] {
  color-scheme: dark;
${colorBlock("dark", "  ")}
}
`;
}

function ts() {
  return `// ${HEADER}
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

export type ThemeName = keyof typeof tokens.colors;
export type ColorToken = keyof typeof tokens.colors.light;
`;
}

function labelsTs() {
  const body = Object.entries(labels)
    .map(([k, v]) => `  ${camel(k)}: ${JSON.stringify(v)},`)
    .join("\n");
  return `// ${HEADER}
export const labels = {
${body}
} as const;

export type Role = "host" | "uploader" | "viewer";

export function roleLabel(role: Role): string {
  switch (role) {
    case "host":
      return labels.roleHost;
    case "uploader":
      return labels.roleUploader;
    case "viewer":
      return labels.roleViewer;
  }
}
`;
}

function dartTokens() {
  const keys = Object.keys(tokens.colors.light);
  const theme = (name) =>
    `  static const ${name} = LocaleColors._(\n${keys
      .map((k) => `    ${k}: Color(${dartHex(tokens.colors[name][k])}),`)
      .join("\n")}\n  );`;
  const consts = (cls, obj) =>
    `abstract final class ${cls} {\n${Object.entries(obj)
      .map(([k, v]) => `  static const double ${/^\d/.test(k) ? `s${k}` : k} = ${v};`)
      .join("\n")}\n}`;
  return `// ${HEADER}
import 'package:flutter/painting.dart';

class LocaleColors {
  const LocaleColors._({
${keys.map((k) => `    required this.${k},`).join("\n")}
  });

${keys.map((k) => `  final Color ${k};`).join("\n")}

${theme("light")}

${theme("dark")}
}

${consts("LocaleSpacing", tokens.spacing)}

${consts("LocaleRadius", tokens.radius)}

${consts("LocaleTextSize", tokens.type.sizes)}
`;
}

function dartLabels() {
  return `// ${HEADER}
abstract final class Labels {
${Object.entries(labels)
  .map(([k, v]) => `  static const String ${camel(k)} = '${v}';`)
  .join("\n")}
}
`;
}

export function build() {
  return {
    [resolve(root, "src/tokens.css")]: css(),
    [resolve(root, "src/tokens.ts")]: ts(),
    [resolve(root, "src/labels.ts")]: labelsTs(),
    [resolve(repo, "apps/mobile/lib/theme/tokens.g.dart")]: dartTokens(),
    [resolve(repo, "apps/mobile/lib/l10n/labels.g.dart")]: dartLabels(),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = build();
  if (process.argv.includes("--check")) {
    const stale = Object.entries(files).filter(([p, c]) => {
      try {
        return readFileSync(p, "utf8") !== c;
      } catch {
        return true;
      }
    });
    if (stale.length > 0) {
      console.error(
        `Generated files are stale: ${stale.map(([p]) => p.replace(repo + "/", "")).join(", ")}.\nRegenerate with: ${COMMAND}`,
      );
      process.exit(1);
    }
  } else {
    for (const [p, c] of Object.entries(files)) {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, c);
    }
  }
}
